from pathlib import Path
import hashlib
root=Path(__file__).resolve().parents[1]
libs=['js/vendor/d3-array.min.js','js/vendor/d3-geo.min.js','js/vendor/topojson-client.min.js']
content='/* Generated by scripts/build-hero.py; edit the vendor sources. */\n'+'\n;\n'.join((root/f).read_text() for f in libs)
(root/'js/globe-libs.js').write_text(content)
source=(root/'js/intro.js').read_text()
import re
source=re.sub(r'globe-libs.js\?v=[a-f0-9]+','globe-libs.js?v='+hashlib.sha256(content.encode()).hexdigest()[:12],source)
(root/'js/intro.js').write_text(source)
(root/'js/hero-scene.js').write_text('/* Generated by scripts/build-hero.py; edit the source files. */\n'+source)
