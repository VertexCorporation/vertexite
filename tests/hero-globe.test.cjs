class RecordedPath {
 constructor(){this.commands=[];}
 moveTo(...p){this.commands.push(['moveTo',...p]);}
 lineTo(...p){this.commands.push(['lineTo',...p]);}
 arc(...p){this.commands.push(['arc',...p]);}
 closePath(){this.commands.push(['closePath']);}
}
class RecordedContext extends RecordedPath {
 constructor(){super();this.ops=[];this.globalAlpha=1;this.stack=[];}
 clearRect(){this.ops=[];}
 beginPath(){this.commands=[];}
 fill(path){this.ops.push(['fill',this.fillStyle,this.globalAlpha,(path||this).commands]);}
 stroke(path){this.ops.push(['stroke',this.strokeStyle,this.lineWidth,this.globalAlpha,(path||this).commands]);}
 save(){this.stack.push([this.globalAlpha,this.fillStyle,this.strokeStyle,this.lineWidth]);}
 restore(){[this.globalAlpha,this.fillStyle,this.strokeStyle,this.lineWidth]=this.stack.pop();}
 drawImage(canvas){this.ops.push(...canvas.ctx.ops);}
}
